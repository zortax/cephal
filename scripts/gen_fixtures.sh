#!/bin/sh
# Generates tests/fixtures/cephal.xml from cephal's own HTML fixtures (tests/fixtures/html/*.html) by
# rendering them in Chrome for Testing through taffy's gentest, in the same format as taffy's
# fixtures. Write fixtures in taffy's HTML format: `div`s are `display: flex; position: relative`
# unless they say otherwise, and `#test-root` is the root (see taffy's test_fixtures).
#
#   scripts/gen_fixtures.sh
set -e
root=$(cd "$(dirname "$0")/.." && pwd)
work="$root/target/gentest/taffy"
[ -d "$work" ] || git -c advice.detachedHead=false clone -q --depth 1 --branch v0.15.0 https://github.com/DioxusLabs/taffy "$work"
rm -rf "$work/test_fixtures" "$work/tests/xml"
mkdir -p "$work/test_fixtures/cephal"
cp "$root"/tests/fixtures/html/*.html "$work/test_fixtures/cephal/"
(cd "$work/scripts/gentest" && RUST_LOG=info cargo run -q --release >"$work/gentest.log" 2>&1) || { cat "$work/gentest.log"; exit 1; }
chrome=$(grep -o 'using chrome-for-testing [0-9.]*' "$work/gentest.log" | head -1)
out="$root/tests/fixtures/cephal.xml"
{
	echo "<!-- Generated by scripts/gen_fixtures.sh from tests/fixtures/html, $chrome. -->"
	echo "<tests>"
	LC_ALL=C ls "$work/tests/xml/cephal" | grep '\.xml$' | while read -r f; do cat "$work/tests/xml/cephal/$f"; done
	echo "</tests>"
} >"$out"
echo "$(grep -c '<test ' "$out") tests ($chrome)"
